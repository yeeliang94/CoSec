// Copies SSM mTool's own list wording into the app, so values written to the AR1 workbook match
// mTool's pickers exactly. Run on a PC with mTool v2.2 installed:
//   node scripts/import-mtool-lists.mjs ["C:\SSM XBRL Preparation Tool"]
// Writes src/domain/ar1/mtool-lists.ts and src/domain/ar1/msic-codes.ts. Review the diff before
// committing: a new mTool release may change wording that existing records already hold.
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const root = process.argv[2] ?? 'C:\\SSM XBRL Preparation Tool';
const read = (path) => readFileSync(join(root, path), 'utf8').replace(/^\uFEFF/, '');
const decode = (s) =>
  s
    .replace(/&quot;/g, '"')
    .replace(/&apos;/g, "'")
    .replace(/&lt;/g, '<')
    .replace(/&gt;/g, '>')
    .replace(/&amp;/g, '&');

const dropdowns = read('CommonFiles/CustomDropdown.xml');
function list(type) {
  const block = new RegExp(
    `<Dropdown[^>]*DropdownType="${type}"[^>]*>([\\s\\S]*?)</Dropdown>`,
  ).exec(dropdowns);
  if (!block) throw new Error(`mTool list ${type} not found`);
  const values = [...block[1].matchAll(/<Value\s+Desc="([^"]*)"/g)].map((m) => decode(m[1]).trim());
  return [...new Set(values.filter(Boolean))];
}
const byName = (values, first = []) => [
  ...first.filter((v) => values.includes(v)),
  ...values.filter((v) => !first.includes(v)).sort((a, b) => a.localeCompare(b, 'en')),
];

// Individuals' identification types, in the order the AR1 prototype offers them; the rest of
// mTool's TypeOfIdentification list is for bodies corporate.
const PERSON_ID = [
  'MyKad',
  'MyPR',
  'MyKAS',
  'Passport number',
  'Military ID number',
  'Police ID number',
  'Old IC number',
  'Official Receiver ID number',
  'Non-citizen without passport number',
];
const identification = list('TypeOfIdentification');
const missing = PERSON_ID.filter((v) => !identification.includes(v));
if (missing.length) throw new Error(`mTool no longer lists ${missing.join(', ')}`);
const RACE_ORDER = ['MALAY', 'CHINESE', 'INDIAN'];

const lists = {
  COUNTRIES: byName(list('Country'), ['MALAYSIA']),
  NATIONALITIES: byName(list('Nationality'), ['MALAYSIA']),
  STATES: byName(list('State')),
  TITLES: byName(list('Title')),
  RACES: byName(list('Race'), RACE_ORDER),
  GENDERS: list('Gender'),
  PERSON_ID_TYPES: PERSON_ID,
  ORGANISATION_ID_TYPES: byName(
    identification.filter((v) => !PERSON_ID.includes(v)),
    ['Company Registration No.', 'LLP Registration No.', 'Foreign Entity Not Registered with SSM'],
  ),
  PROFESSIONAL_TYPES: list('ProfessionalType'),
  CURRENCIES: byName(list('DescriptionOfFunctionalCurrency'), ['Malaysian Ringgit (MYR)']),
  BO_EXEMPT_CATEGORIES: list('CertifyThatCategoryOfCompanyExemptedFromBeneficialOwnerReporting'),
};

// Enumerations defined by SSM's taxonomy rather than mTool's pickers.
const fdn = read(
  'Taxonomy/https/mbrs.ssm.com.my/taxonomy/SSMxT2022v1.0/def/fdn/ssmt-fdn_2022-12-31.xsd',
);
function enumeration(type) {
  const block = new RegExp(
    `<(?:xsd?:)?(?:simpleType|complexType)[^>]*name="${type}"[\\s\\S]*?</(?:xsd?:)?(?:simpleType|complexType)>`,
  ).exec(fdn);
  if (!block) throw new Error(`taxonomy type ${type} not found`);
  return [...block[0].matchAll(/enumeration value="([^"]*)"/g)].map((m) => decode(m[1]));
}
Object.assign(lists, {
  ORIGINS: enumeration('OriginOfCompany'),
  COMPANY_STATUSES: enumeration('StatusOfCompany').reverse(),
  COMPANY_TYPES: enumeration('TypeOfCompany'),
  MEMBER_BANDS: enumeration('NumberOfMembersOfPublicCompany').reverse(),
  APPLICATIONS: enumeration('ApplicationOfSubmissionType'),
  MEMBER_TYPES: enumeration('ShareholderType'),
  SUBCLASSIFICATION_TYPES: enumeration('SubclassificationShareholderType'),
  TRUSTEE_TYPES: enumeration('TrusteeType'),
  BO_STATUSES: enumeration('CertifyThatStatusRelatingToBeneficialOwnersOfCompanyType'),
  NOMINEE_STATUSES: enumeration('CertifyThatCompanyHasFollowingStatusRelatingToItsDirectorType'),
});

const ts = (name, values) =>
  `export const ${name} = [\n${values.map((v) => `  ${JSON.stringify(v)},`).join('\n')}\n] as const;\n`;
writeFileSync(
  'src/domain/ar1/mtool-lists.ts',
  `// Generated by scripts/import-mtool-lists.mjs from mTool v2.2's CommonFiles/CustomDropdown.xml\n` +
    `// and SSM taxonomy SSMxT_2022v1.0 (def/fdn/ssmt-fdn_2022-12-31.xsd).\n` +
    `// mTool stores each value's exact wording; do not edit by hand.\n\n` +
    Object.entries(lists)
      .map(([name, values]) => ts(name, values))
      .join('\n'),
);

const msic = [
  ...read('CommonFiles/MSIC.xml').matchAll(
    /<item\s+MSICCode="([^"]+)"[^>]*EnglishDescription="([^"]*)"/g,
  ),
]
  .map((m) => [m[1].trim(), decode(m[2]).replace(/\s+/g, ' ').trim()])
  .filter(([code]) => /^\d{5}[a-z]?$/.test(code));
const seen = new Set();
const unique = msic
  .filter(([code]) => !seen.has(code) && seen.add(code))
  .sort((a, b) => a[0].localeCompare(b[0], 'en'));
writeFileSync(
  'src/domain/ar1/msic-codes.ts',
  `// Generated by scripts/import-mtool-lists.mjs from mTool v2.2's CommonFiles/MSIC.xml.\n` +
    `// [code, English description]; mTool's picker shows "<code> <description>". Server use only.\n\n` +
    `export const MSIC_CODES: readonly (readonly [string, string])[] = [\n` +
    unique.map(([c, d]) => `  [${JSON.stringify(c)}, ${JSON.stringify(d)}],`).join('\n') +
    `\n];\n`,
);
console.log(
  Object.entries(lists)
    .map(([n, v]) => `${n}: ${v.length}`)
    .concat(`MSIC_CODES: ${unique.length}`)
    .join('\n'),
);
